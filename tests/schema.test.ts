function connection(name: string, dialect: ConnectionModel['dialect']): ConnectionModel {
    return {
        name,
        dialect,
        defaultSchema: 'public',
        read: { schemas: ['public'], features: { tables: 'complete', columns: 'complete', checkConstraints: 'partial' } },
        tables: [users(name)],
    };
}

function model(connections: ConnectionModel[]): SchemaModel {
    const first = connections.map((c) => c.name).sort()[0] ?? '';
    return {
        source: 'database',
        producer: 'node-schema-viewer',
        orm: null,
        connections,
        entities: [],
        associations: [],
        diagnostics: [
            {
                kind: 'write_privileges',
                category: 'inspection',
                severity: 'warning',
                certainty: 'certain',
                subject: { type: 'connection', id: `connection:${first}`, columns: null, label: first },
                message: 'Inspected with a role that can change the schema or data.',
            },
        ],
    };
}

describe('serialize', () => {
    test('writes a strictly valid 2.0 document with the shared links, diagnostic ids and the new arrays', () => {
        const document = serialize(model([connection('default', 'postgresql')]));
        assertProducerDocument(document);
        assert.equal(document.version, '2.0');
        assert.deepEqual([document.comparisons, document.migrations, document.inferredAssociations], [[], [], []]);
        const [c] = document.connections;
        assert.equal(c?.driver, 'postgresql');
        assert.deepEqual(c.coverage, { database: { complete: false, schemas: ['public'], features: { tables: 'complete', columns: 'complete', checkConstraints: 'partial' } }, declared: null });
        const [diagnostic] = document.diagnostics;
        assert.ok(diagnostic);
        assert.equal(diagnostic.id, diagnosticId(diagnostic));
        assert.equal(document.links.length, 1);
        const table = c.tables[0];
        const primary = table?.indexes.find((i) => i.name === 'users_pkey');
        assert.deepEqual(primary?.backs, { kind: 'primary_key', constraint: null });
        assert.ok(!('columns' in primary) && !('primary' in primary));
        const expression = table?.indexes.find((i) => i.name === 'users_manager_lower');
        assert.deepEqual(
            [expression?.expression, expression?.partial, expression?.parts[0]?.length, expression?.dialectOptions],
            [true, true, null, { postgresql: { options: { nullsNotDistinct: true } } }],
        );
        assert.deepEqual(table?.columns[0]?.default, { kind: 'identity', value: 'GENERATED BY DEFAULT AS IDENTITY' });
        assert.deepEqual(table.constraints[0]?.provenance, ['database']);
    });

    test('refuses a model that would not be a valid document', () => {
        const broken = connection('default', 'postgresql');
        const table = broken.tables[0];
        const fk = table?.foreignKeys[0];
        assert.ok(table && fk);
        table.foreignKeys[0] = { ...fk, referencedTable: tableId('default', null, 'missing') };
        assert.throws(() => serialize(model([broken])), /foreign/i);
    });

    test('equal models serialize to equal bytes, in any input order', () => {
        const a = serialize(model([connection('b', 'mysql'), connection('a', 'sqlite')]));
        const b = serialize(model([connection('a', 'sqlite'), connection('b', 'mysql')]));
        assert.equal(canonicalJson(a), canonicalJson(b));
        assert.deepEqual(a.connections.map((c) => c.name), ['a', 'b']);
    });

    test('sorts by Unicode code point', () => {
        assert.ok(byCodePoint('￿', '\u{10000}') < 0);
        assert.ok(byCodePoint('a', 'ab') < 0);
        assert.equal(byCodePoint('x', 'x'), 0);
    });
});

describe('merge', () => {
    test('puts connections side by side, rebuilds the graph and validates strictly', () => {
        const merged = merge([serialize(model([connection('local', 'sqlite')])), serialize(model([connection('analytics', 'mariadb')]))]);
        assertProducerDocument(merged);
        assert.deepEqual(merged.connections.map((c) => [c.name, c.driver]), [['analytics', 'mariadb'], ['local', 'sqlite']]);
        assert.equal(merged.links.length, 2);
        assert.equal(merged.diagnostics.length, 2);
    });

    test('refuses duplicate connections, other sources and nothing', () => {
        const one = serialize(model([connection('default', 'postgresql')]));
        assert.throws(() => merge([one, one]), /duplicate|unique/i);
        assert.throws(() => merge([one, { ...one, source: 'declared' }]), /one source/);
        assert.throws(() => merge([]), /Nothing to merge/);
    });
});

describe('layering', () => {
    test('catalog readers build the internal model and never write document fields', () => {
        const directory = join(ROOT, 'src', 'introspection');
        for (const name of ['postgresql.ts', 'mysql.ts', 'sqlite.ts', 'common.ts', 'catalog.ts']) {
            const source = readFileSync(join(directory, name), 'utf8');
            for (const field of ['provenance', 'foreignTable', 'foreignColumns', 'typeName:', 'backs:', 'opclass:', 'ormDefault', 'coverage:', 'driver:']) {
                assert.ok(!source.includes(field), `${name} writes ${field}`);
            }
        }
        assert.ok(readdirSync(directory).includes('catalog.ts'));
    });

    test('ORM adapters build the internal model and never write document fields', () => {
        const directory = join(ROOT, 'src', 'isolation', 'extractors');
        const adapters = readdirSync(directory).filter((name) => name.endsWith('.ts'));
        assert.deepEqual(adapters, ['declared.ts', 'drizzle.ts']);
        for (const name of adapters) {
            const source = readFileSync(join(directory, name), 'utf8');
            // foreignTable and foreignColumns are also Drizzle's own names, read from its foreign keys.
            for (const field of ['provenance', 'typeName:', 'backs:', 'opclass:', 'ormDefault', 'coverage:', 'className', 'relatedModel', 'relatedTable', 'readOnly', 'collection:', 'derivedLinks', 'inferredAssociations']) {
                assert.ok(!source.includes(field), `${name} writes ${field}`);
            }
        }
    });
});
