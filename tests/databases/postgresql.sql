-- Synthetic schema for the PostgreSQL introspection tests: two schemas, composite keys, every index feature.
CREATE SCHEMA billing;
CREATE TYPE account_status AS ENUM ('trial', 'active', 'closed');

CREATE TABLE accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email text NOT NULL UNIQUE,
    external_ref uuid NOT NULL,
    status account_status NOT NULL DEFAULT 'trial',
    tags text[] NOT NULL DEFAULT '{}',
    data jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now(),
    deleted_at timestamptz,
    search tsvector GENERATED ALWAYS AS (to_tsvector('simple', email)) STORED
);
COMMENT ON TABLE accounts IS 'Customer accounts';
COMMENT ON COLUMN accounts.email IS 'Login address';
CREATE UNIQUE INDEX accounts_external_ref_key ON accounts (external_ref) NULLS NOT DISTINCT;
CREATE UNIQUE INDEX accounts_lower_email_idx ON accounts (lower(email));
CREATE UNIQUE INDEX accounts_live_email_idx ON accounts (email) WHERE deleted_at IS NULL;
CREATE INDEX accounts_created_at_idx ON accounts (created_at DESC NULLS LAST) INCLUDE (status);
CREATE INDEX accounts_status_created_idx ON accounts (status, date_trunc('day', created_at AT TIME ZONE 'UTC'));
CREATE INDEX accounts_email_pattern_idx ON accounts (email COLLATE "C" text_pattern_ops);
CREATE INDEX accounts_tags_idx ON accounts USING gin (tags);
CREATE INDEX accounts_data_idx ON accounts USING gin (data jsonb_path_ops);

CREATE TABLE billing.invoices (
    id serial PRIMARY KEY,
    account_id bigint NOT NULL REFERENCES accounts (id) ON DELETE CASCADE,
    number integer NOT NULL,
    total numeric(12, 2) NOT NULL CHECK (total >= 0),
    UNIQUE (account_id, number)
);

-- Composite primary key, and a composite foreign key onto it.
CREATE TABLE billing.invoice_lines (
    invoice_id integer NOT NULL REFERENCES billing.invoices (id),
    line_no smallint NOT NULL,
    amount numeric(12, 2) NOT NULL,
    PRIMARY KEY (invoice_id, line_no)
);
CREATE TABLE billing.line_notes (
    id serial PRIMARY KEY,
    invoice_id integer NOT NULL,
    line_no smallint NOT NULL,
    body varchar(500),
    CONSTRAINT line_notes_line_fkey FOREIGN KEY (invoice_id, line_no)
        REFERENCES billing.invoice_lines (invoice_id, line_no) ON UPDATE CASCADE DEFERRABLE INITIALLY DEFERRED
);
